import { useState } from "react";

import { Chip } from "../../components/ui";
import { PRIORITY_TONE, VERDICT, procedureLabel, type Triage } from "../../lib/agent";

/** A triage report: the agent's proposal, with one approve/reject per recommendation. */
export function TriageView({
  report,
  onDecide,
  busy,
}: {
  report: Triage;
  onDecide: (index: number, decision: "approved" | "rejected") => void;
  busy?: boolean;
}) {
  const [showReport, setShowReport] = useState(false);
  const verdict = VERDICT[report.verdict];
  return (
    <div className="flex flex-col gap-2 text-[12.5px]">
      <div className="flex items-center gap-2">
        <Chip tone={verdict.tone}>{verdict.label}</Chip>
        <span className="font-mono text-[11px] text-fg-dim">
          confidence {Math.round(report.confidence * 100)}%
        </span>
      </div>
      <p className="leading-snug text-fg">{report.summary}</p>
      <p className="text-fg-muted">
        <span className="hud-title mr-1">Likely cause</span>
        {report.likely_cause}
      </p>
      <ol className="flex flex-col gap-1.5" aria-label="Recommended actions">
        {report.recommended_actions.map((a, i) => (
          <li
            key={`${String(i)}-${a.action}`}
            className="border-l-2 pl-2"
            style={{ borderColor: PRIORITY_TONE[a.priority] }}
          >
            <div className="flex items-start justify-between gap-2">
              <span className="text-fg">{a.action}</span>
              {a.decision ? (
                <Chip
                  tone={a.decision === "approved" ? "var(--color-phosphor)" : "var(--color-fg-dim)"}
                >
                  {a.decision}
                </Chip>
              ) : (
                <span className="flex shrink-0 gap-1">
                  <button
                    type="button"
                    className="btn-primary"
                    disabled={busy}
                    onClick={() => {
                      onDecide(i, "approved");
                    }}
                  >
                    Approve
                  </button>
                  <button
                    type="button"
                    className="btn-ghost"
                    disabled={busy}
                    onClick={() => {
                      onDecide(i, "rejected");
                    }}
                  >
                    Reject
                  </button>
                </span>
              )}
            </div>
            <div className="text-[11.5px] text-fg-dim">
              {a.priority} · {a.rationale}
              {a.procedure_ref ? ` · ${procedureLabel(a.procedure_ref)}` : ""}
            </div>
          </li>
        ))}
      </ol>
      {report.cited_procedures.length > 0 && (
        <div className="flex flex-wrap items-center gap-1">
          <span className="hud-title mr-1">Cites</span>
          {report.cited_procedures.map((p) => (
            <Chip key={p}>{procedureLabel(p)}</Chip>
          ))}
        </div>
      )}
      <button
        type="button"
        className="btn-ghost self-start"
        onClick={() => {
          setShowReport((v) => !v);
        }}
      >
        {showReport ? "Hide incident report draft" : "Incident report draft"}
      </button>
      {showReport && (
        <div className="flex flex-col gap-1">
          <pre className="max-h-48 overflow-y-auto whitespace-pre-wrap bg-ink-900 p-2 font-mono text-[11px] text-fg-muted">
            {report.incident_report}
          </pre>
          <button
            type="button"
            className="btn-primary self-start"
            onClick={() => void navigator.clipboard.writeText(report.incident_report)}
          >
            Copy
          </button>
        </div>
      )}
      <div className="font-mono text-[10px] text-fg-dim">
        AI-generated by {report.model} in {(report.latency_ms / 1000).toFixed(1)} s · looked at{" "}
        {report.tool_calls.join(", ")} · verify before acting
      </div>
    </div>
  );
}
